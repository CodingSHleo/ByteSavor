FALLBACK = "选色泽正常、无异味、外观完整的"


def get_tip(name: str) -> str:
    for key, tip in TIPS.items():
        if key in name or name in key:
            return tip
    return FALLBACK


def enrich_shopping_list(items: list[dict]) -> list[dict]:
    """给购物清单每项加上挑选建议"""
    for item in items:
        name = item.get("name", "")
        item["tip"] = get_tip(name)
    return items
